// The field's blossom color at photo (u, v): the enclosing cell's mean when that is a blossom color,
// otherwise the nearest such cell's hue and saturation at this cell's own lightness (so a blossom on a
// lavender strand-end cell stays pink but as light as the photo is there).
export function canopyColorAt(u, v) {
  const F = CANOPY_FIELD;
  const w = F.c1 - F.c0 + 1;
  const h = F.r1 - F.r0 + 1;
  let c = Math.floor(u * F.cols) - F.c0;
  let r = Math.floor(v * F.rows) - F.r0;
  c = Math.max(0, Math.min(w - 1, c));
  r = Math.max(0, Math.min(h - 1, r));
  if (!F.own[r * w + c]) {
    let best = -1;
    let bestD = Infinity;
    for (let rr = 0; rr < h; rr++) {
      for (let cc = 0; cc < w; cc++) {
        if (!F.own[rr * w + cc]) continue;
        const d = (rr - r) * (rr - r) + (cc - c) * (cc - c);
        if (d < bestD) {
          bestD = d;
          best = rr * w + cc;
        }
      }
    }
    if (best >= 0) return withLightnessOf(parseInt(F.hex[best].slice(1), 16), parseInt(F.hex[r * w + c].slice(1), 16));
  }
  return parseInt(F.hex[r * w + c].slice(1), 16);
}

// Returns hex with its lightness replaced by that of reference (HSL on the sRGB values).
function withLightnessOf(hex, reference) {
  const [h, s] = toHsl(hex);
  const [, , l] = toHsl(reference);
  return fromHsl(h, s, l);
}

function toHsl(hex) {
  const r = ((hex >> 16) & 255) / 255;
  const g = ((hex >> 8) & 255) / 255;
  const b = (hex & 255) / 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h;
  if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
  else if (max === g) h = (b - r) / d + 2;
  else h = (r - g) / d + 4;
  return [h / 6, s, l];
}

function fromHsl(h, s, l) {
  const f = (n) => {
    const k = (n + h * 12) % 12;
    const a = s * Math.min(l, 1 - l);
    return l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1));
  };
  return (Math.round(f(0) * 255) << 16) | (Math.round(f(8) * 255) << 8) | Math.round(f(4) * 255);
}

// Whether photo (u, v) lies on a blossom cell, with `margin` extra cells of tolerance around the mask.
export function canopyMaskAt(u, v, margin = 0) {
  const F = CANOPY_FIELD;
  const w = F.c1 - F.c0 + 1;
  const h = F.r1 - F.r0 + 1;
  const c = Math.floor(u * F.cols) - F.c0;
  const r = Math.floor(v * F.rows) - F.r0;
  for (let dr = -margin; dr <= margin; dr++) {
    for (let dc = -margin; dc <= margin; dc++) {
      const rr = r + dr;
      const cc = c + dc;
      if (rr < 0 || cc < 0 || rr >= h || cc >= w) continue;
      if (F.pink[rr * w + cc]) return true;
    }
  }
  return false;
}
